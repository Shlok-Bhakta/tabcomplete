#!/usr/bin/env bash
# Start the trajectory collector (idempotent).
# - Verifies docker + tailscale CLIs exist.
# - Resolves the Tailnet bind IP via `tailscale ip -4` unless
#   TABCOMPLETE_TAILSCALE_BIND_ADDR is already set/exported.
# - Writes an untracked deployment .env next to docker-compose.yml.
# - Runs `docker compose up -d --build`, waits for /healthz, prints private URL.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

if ! command -v docker >/dev/null 2>&1; then
  echo "error: docker CLI not found (podman shim expected)" >&2
  exit 1
fi
if ! command -v tailscale >/dev/null 2>&1; then
  echo "error: tailscale CLI not found" >&2
  exit 1
fi
if ! tailscale status >/dev/null 2>&1; then
  echo "error: tailscale does not appear to be up (tailscale status failed)" >&2
  exit 1
fi

PORT="${TABCOMPLETE_COLLECTOR_PORT:-8787}"
HOST_NAME="${TABCOMPLETE_TAILSCALE_HOST:-crabcake}"

BIND_ADDR="${TABCOMPLETE_TAILSCALE_BIND_ADDR:-}"
if [ -z "$BIND_ADDR" ]; then
  if [ -f "$ROOT_DIR/.env" ]; then
    # Preserve an existing deployment bind address (do not clobber).
    # shellcheck disable=SC1091
    set -a
    # shellcheck source=/dev/null
    source "$ROOT_DIR/.env"
    set +a
    BIND_ADDR="${TABCOMPLETE_TAILSCALE_BIND_ADDR:-}"
  fi
fi
if [ -z "$BIND_ADDR" ]; then
  BIND_ADDR="$(tailscale ip -4)"
  # `tailscale ip -4` may print multiple addresses; take the first.
  BIND_ADDR="$(printf '%s\n' "$BIND_ADDR" | head -n 1 | tr -d '[:space:]')"
fi
if [ -z "$BIND_ADDR" ]; then
  echo "error: could not determine Tailscale bind address" >&2
  exit 1
fi

# Refuse loopback/unspecified publishes: Tailnet-only binding.
if [ "$BIND_ADDR" = "0.0.0.0" ] || [ "$BIND_ADDR" = "127.0.0.1" ] || [ "$BIND_ADDR" = "::" ]; then
  echo "error: refusing to bind collector to '$BIND_ADDR' (must be a Tailnet IP)" >&2
  exit 1
fi

export TABCOMPLETE_TAILSCALE_BIND_ADDR="$BIND_ADDR"
export TABCOMPLETE_TAILSCALE_HOST="$HOST_NAME"
export TABCOMPLETE_COLLECTOR_PORT="$PORT"

# SSD-backed data dir (SQLite lives here).
mkdir -p /mnt/ssd/collector-data

# Write untracked deployment .env (idempotent: same content rewritten).
cat > "$ROOT_DIR/.env" <<EOF
# Generated by scripts/start.sh — untracked deployment config. Do not commit.
TABCOMPLETE_TAILSCALE_HOST=$HOST_NAME
TABCOMPLETE_TAILSCALE_BIND_ADDR=$BIND_ADDR
TABCOMPLETE_COLLECTOR_PORT=$PORT
EOF

docker compose up -d --build

# Wait for health (up to ~60s).
HEALTH_URL="http://${BIND_ADDR}:${PORT}/healthz"
for i in $(seq 1 60); do
  if curl -fsS --max-time 2 "$HEALTH_URL" >/dev/null 2>&1; then
    echo "collector healthy at $HEALTH_URL"
    echo "private URL: http://${BIND_ADDR}:${PORT}"
    exit 0
  fi
  sleep 1
done

echo "error: collector did not become healthy at $HEALTH_URL" >&2
docker compose ps >&2 || true
exit 1
